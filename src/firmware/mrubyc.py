"""mruby/c support: generated config header + bytecode, and the ``fw.mrubyc`` gate.

``firmware mrubyc <contract>`` regenerates the VM config header
(``fw_mruby.h``), one ``*_bytecode.c`` per authored ``.rb`` (via the pinned
``mrbc``), and ``fw_ruby_manifest.json`` binding every source to its sha256.
The static gate compares regenerated output byte-for-byte so a hand-edited or
stale artifact fails, and it verifies the UX manifest pin plus the VM feature
flags the Ruby sources actually need.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field

from .contract import FirmwareContract, MrubycConfig, resolve
from .interchange import sha256_file
from .profiles import McuProfile
from .projections import write_bytes, write_text

MANIFEST_NAME = "fw_ruby_manifest.json"
MRUBYC_REF_FILE = "/opt/mrubyc/REF"

# Upstream hal/<name> dir -> build backends able to compile that HAL.
HAL_BACKENDS: dict[str, frozenset[str]] = {
    "avr": frozenset({"make"}),
    "emscripten": frozenset({"make"}),
    "esp32": frozenset({"platformio"}),
    "pic24": frozenset({"make"}),
    "posix": frozenset({"make", "cmake"}),
    "psoc5lp": frozenset({"make"}),
    "rp2040": frozenset({"cmake"}),
    "stm32": frozenset({"make", "cmake", "west"}),
    "zephyr": frozenset({"west"}),
}


class MrubyManifestFile(BaseModel):
    model_config = ConfigDict(extra="forbid")

    file: str = Field(min_length=1)
    sha256: str = Field(pattern=r"^[0-9a-f]{64}$")


class MrubyManifestRequires(BaseModel):
    model_config = ConfigDict(extra="forbid")

    float: int = Field(default=0, ge=0, le=2)
    math: bool = False
    string: bool = True
    utf8: bool = False
    tick: bool = True


class MrubyUxManifestDoc(BaseModel):
    """The ux-creator ``*.mruby-manifest.json`` this contract pins."""

    model_config = ConfigDict(extra="forbid")

    schema_version: int = 1
    artifact_kind: str = "mruby_manifest"
    product: str = Field(min_length=1)
    files: list[MrubyManifestFile]
    requires: MrubyManifestRequires = Field(default_factory=MrubyManifestRequires)
    classes: list[str] = Field(default_factory=list[str])


_FLOAT_RE = re.compile(r"(?<![\w.'])\d+\.\d+(?![\w'])|\.to_f\b|\bFloat\b")
_MATH_RE = re.compile(r"\bMath\.")
_STRING_RE = re.compile(
    r"\bString\b|\.to_s\b|\.(size|length|strip|lstrip|rstrip|split|gsub|sub|upcase|"
    r"downcase|chars|bytes|slice|index|rindex|start_with\?|end_with\?|include\?|"
    r"center|ljust|rjust|tr|chomp|chop|reverse|succ|ord|chr|hex|oct|format|sprintf|"
    r"capitalize|swapcase|count|delete|squeeze|insert|replace|empty\?|eql\?)\b|#\{"
)
_TICK_RE = re.compile(r"\bVM\.tick\b|\bsleep_ms\b|\bVM\.sleep\b|(^|[^.\w])sleep\b")


def feature_scan(source: str, cfg: MrubycConfig) -> list[str]:
    """Flag Ruby constructs the configured VM cannot run."""
    problems: list[str] = []
    if cfg.use_float == 0 and _FLOAT_RE.search(source):
        problems.append("uses Float while use_float=0")
    if not cfg.use_math and _MATH_RE.search(source):
        problems.append("uses Math while use_math is false")
    if not cfg.use_string and _STRING_RE.search(source):
        problems.append("uses String while use_string is false")
    if cfg.no_timer and _TICK_RE.search(source):
        problems.append("uses VM.tick/sleep while no_timer is true")
    return problems


def config_header(cfg: MrubycConfig, contract_name: str) -> str:
    """Deterministic ``fw_mruby.h`` content mirroring the vm_config.h flags."""
    lines = [
        "/* Auto-generated by `firmware mrubyc`; do not edit by hand.",
        f" * contract: {contract_name}   mrubyc ref: {cfg.ref}",
        " * Regenerate: `firmware mrubyc <name>.fw.json`",
        " */",
        "#ifndef FW_MRUBY_H",
        "#define FW_MRUBY_H",
        "",
        "/* VM heap passed to mrbc_init_alloc(pool, FW_MRUBY_MEMORY_SIZE). */",
        f"#define FW_MRUBY_MEMORY_SIZE {cfg.memory_size}u",
        "",
        f"#define MRBC_TICK_UNIT {cfg.tick_unit_ms}",
        "#define MRBC_TIMESLICE_TICK_COUNT 1",
    ]
    if cfg.no_timer:
        lines.append("#define MRBC_NO_TIMER")
    lines += [
        f"#define MRBC_USE_FLOAT {cfg.use_float}",
        f"#define MRBC_USE_MATH {1 if cfg.use_math else 0}",
        f"#define MRBC_USE_STRING {1 if cfg.use_string else 0}",
        f"#define MRBC_USE_STRING_UTF8 {1 if cfg.use_utf8 else 0}",
        f"#define MAX_VM_COUNT {cfg.max_vm_count}",
        "",
        "#endif /* FW_MRUBY_H */",
        "",
    ]
    return "\n".join(lines)


def _mrbc() -> str | None:
    return shutil.which("mrbc")


def compile_bytecode(mrbc: str, symbol: str, source: Path, timeout: int = 60) -> bytes:
    """Run ``mrbc -B`` and return the generated C source bytes."""
    proc = subprocess.run(
        [mrbc, "-B", symbol, "--remove-lv", "-o", "-", str(source)],
        capture_output=True,
        timeout=timeout,
        check=False,
    )
    if proc.returncode != 0:
        detail = proc.stderr.decode("utf-8", "replace").strip() or "mrbc -B failed"
        raise RuntimeError(f"{source.name}: {detail}")
    return proc.stdout


def syntax_check(mrbc: str, source: Path, timeout: int = 30) -> str | None:
    """``mrbc -c`` output error, or None when the source parses."""
    proc = subprocess.run(
        [mrbc, "-c", str(source)], capture_output=True, text=True, timeout=timeout, check=False
    )
    if proc.returncode != 0:
        return proc.stderr.strip() or f"mrbc -c exited {proc.returncode}"
    return None


def ruby_manifest(files: list[dict[str, str]], cfg: MrubycConfig, contract_name: str) -> str:
    doc = {
        "schema_version": 1,
        "artifact_kind": "fw_ruby_manifest",
        "contract": contract_name,
        "mrubyc_ref": cfg.ref,
        "files": files,
    }
    return json.dumps(doc, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def generate(contract: FirmwareContract, contract_path: Path) -> tuple[list[Path], list[str]]:
    """Regenerate the config header, bytecode C files and the source manifest."""
    assert contract.mrubyc is not None
    cfg = contract.mrubyc
    mrbc = _mrbc()
    if mrbc is None:
        return [], ["mrbc not on PATH (mruby toolchain missing)"]
    written: list[Path] = []
    problems: list[str] = []
    header = resolve(contract_path, cfg.config_header)
    written.append(write_text(header, config_header(cfg, contract.name)))
    files: list[dict[str, str]] = []
    for source in cfg.sources:
        source_path = resolve(contract_path, source.file)
        if not source_path.is_file():
            problems.append(f"mruby source {source.file} missing")
            continue
        try:
            blob = compile_bytecode(mrbc, source.symbol, source_path)
        except (RuntimeError, subprocess.TimeoutExpired) as exc:
            problems.append(str(exc))
            continue
        out = resolve(contract_path, source.bytecode)
        written.append(write_bytes(out, blob))
        files.append(
            {
                "file": source.file,
                "sha256": hashlib.sha256(source_path.read_bytes()).hexdigest(),
                "bytecode": source.bytecode,
                "symbol": source.symbol,
            }
        )
    manifest = resolve(contract_path, f"{cfg.generated_dir}/{MANIFEST_NAME}")
    written.append(write_text(manifest, ruby_manifest(files, cfg, contract.name)))
    return written, problems


def _hal_profile_ok(hal: str, profile: McuProfile) -> bool:
    pid = profile.id.lower()
    core = profile.core.lower()
    if hal == "avr":
        return "avr" in core or pid.startswith("avr")
    if hal == "esp32":
        return pid.startswith("esp32")
    if hal == "rp2040":
        return pid in {"rp2040", "rp2350"}
    if hal == "stm32":
        return pid.startswith("stm32")
    if hal == "pic24":
        return pid.startswith("pic24")
    if hal == "psoc5lp":
        return pid.startswith("psoc")
    # zephyr/emscripten/posix fit any Zephyr-supported or simulated target.
    return True


def mrubyc_problems(
    contract: FirmwareContract, profile: McuProfile, contract_path: Path
) -> tuple[list[str], list[str]]:
    """``fw.mrubyc`` static check: pins, freshness, feature flags, toolchain legs."""
    assert contract.mrubyc is not None
    cfg = contract.mrubyc
    problems: list[str] = []
    evidence: list[str] = [f"hal={cfg.hal}", f"ref={cfg.ref}"]

    ref_file = Path(os.environ.get("FIRMWARE_MRUBYC_REF", MRUBYC_REF_FILE))
    if not ref_file.is_file():
        problems.append(f"mrubyc toolchain ref file {ref_file} missing")
    else:
        pinned = ref_file.read_text(encoding="utf-8").strip()
        evidence.append(f"toolchain={pinned}")
        if pinned != cfg.ref:
            problems.append(f"mrubyc ref {cfg.ref} differs from toolchain pin {pinned}")

    if not _hal_profile_ok(cfg.hal, profile):
        problems.append(f"hal {cfg.hal} cannot target profile {profile.id} ({profile.part})")
    legs = [contract.build] + [s.build for s in contract.simulations if s.build is not None]
    backends = {leg.backend for leg in legs}
    allowed = HAL_BACKENDS[cfg.hal]
    if backends.isdisjoint(allowed):
        problems.append(
            f"hal {cfg.hal} needs a {'/'.join(sorted(allowed))} build leg; "
            f"declared backends: {', '.join(sorted(backends)) or 'none'}"
        )
    if cfg.hal == "emscripten" and not any(s.runner == "node" for s in contract.simulations):
        problems.append("hal emscripten needs a node-runner simulation leg")

    limit = int(profile.ram_kb * 1024 * 0.8)
    if cfg.memory_size > limit:
        problems.append(
            f"memory_size {cfg.memory_size} exceeds 80% of {profile.part} RAM ({limit})"
        )

    mrbc = _mrbc()
    if mrbc is None:
        problems.append("mrbc not on PATH (mruby toolchain missing)")
    for source in cfg.sources:
        source_path = resolve(contract_path, source.file)
        if not source_path.is_file():
            problems.append(f"mruby source {source.file} missing")
            continue
        text = source_path.read_text(encoding="utf-8")
        for problem in feature_scan(text, cfg):
            problems.append(f"{source.file}: {problem}")
        if mrbc is None:
            continue
        error = syntax_check(mrbc, source_path)
        if error:
            problems.append(f"{source.file}: mrbc -c: {error}")
            continue
        bytecode_path = resolve(contract_path, source.bytecode)
        if not bytecode_path.is_file():
            problems.append(f"bytecode {source.bytecode} missing; run `firmware mrubyc`")
            continue
        try:
            expected = compile_bytecode(mrbc, source.symbol, source_path)
        except (RuntimeError, subprocess.TimeoutExpired) as exc:
            problems.append(f"{source.file}: {exc}")
            continue
        if bytecode_path.read_bytes() != expected:
            problems.append(f"bytecode {source.bytecode} stale; run `firmware mrubyc`")

    header_path = resolve(contract_path, cfg.config_header)
    if not header_path.is_file():
        problems.append(f"config header {cfg.config_header} missing; run `firmware mrubyc`")
    elif header_path.read_text(encoding="utf-8") != config_header(cfg, contract.name):
        problems.append(f"config header {cfg.config_header} stale; run `firmware mrubyc`")

    manifest_path = resolve(contract_path, f"{cfg.generated_dir}/{MANIFEST_NAME}")
    expected_files = [
        {
            "file": s.file,
            "sha256": hashlib.sha256(resolve(contract_path, s.file).read_bytes()).hexdigest(),
            "bytecode": s.bytecode,
            "symbol": s.symbol,
        }
        for s in cfg.sources
        if resolve(contract_path, s.file).is_file()
    ]
    if not manifest_path.is_file():
        problems.append(f"{MANIFEST_NAME} missing; run `firmware mrubyc`")
    else:
        try:
            doc = json.loads(manifest_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            problems.append(f"{MANIFEST_NAME} unreadable: {exc}")
        else:
            if doc.get("files") != expected_files:
                problems.append(f"{MANIFEST_NAME} stale; run `firmware mrubyc`")

    if cfg.ux_manifest is not None:
        ux_path = resolve(contract_path, cfg.ux_manifest.manifest)
        if not ux_path.is_file():
            problems.append(f"ux manifest {cfg.ux_manifest.manifest} missing")
        else:
            sha = sha256_file(ux_path)
            if sha != cfg.ux_manifest.sha256:
                problems.append(
                    f"ux manifest sha256 {sha} differs from pinned "
                    f"{cfg.ux_manifest.sha256}; review and re-pin"
                )
            else:
                try:
                    ux = MrubyUxManifestDoc.model_validate(
                        json.loads(ux_path.read_text(encoding="utf-8"))
                    )
                except Exception as exc:
                    problems.append(f"ux manifest invalid: {exc}")
                else:
                    evidence.append(f"ux={ux.product} files={len(ux.files)}")
                    req = ux.requires
                    if req.float > cfg.use_float:
                        problems.append(
                            f"ux manifest needs float>={req.float}, "
                            f"contract use_float={cfg.use_float}"
                        )
                    if req.math and not cfg.use_math:
                        problems.append("ux manifest needs Math, contract use_math is false")
                    if req.string and not cfg.use_string:
                        problems.append("ux manifest needs String, contract use_string is false")
                    if req.utf8 and not cfg.use_utf8:
                        problems.append("ux manifest needs UTF-8, contract use_utf8 is false")
                    if req.tick and cfg.no_timer:
                        problems.append(
                            "ux manifest needs the tick timer, contract no_timer is true"
                        )
                    known = {s.file for s in cfg.sources}
                    for entry in ux.files:
                        if entry.file not in known:
                            problems.append(f"ux manifest file {entry.file} not in mrubyc.sources")
                            continue
                        source_path = resolve(contract_path, entry.file)
                        if source_path.is_file():
                            actual = hashlib.sha256(source_path.read_bytes()).hexdigest()
                            if actual != entry.sha256:
                                problems.append(
                                    f"{entry.file}: sha256 {actual} differs from ux manifest pin"
                                )
    return problems, evidence
